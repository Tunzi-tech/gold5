import { createApp } from 'vue'
import './style.css'
import './nfas-sidebar-orbit.css'
import './mobile-impact-dark.css'
import App from './App.vue'

type EnffasEarlyDiagnostics = {
  stage: string
  errors: string[]
  mark: (stage: string) => void
}

const earlyDiagnostics = (window as Window & {
  __ENFFAS_EARLY_DIAGNOSTICS__?: EnffasEarlyDiagnostics
}).__ENFFAS_EARLY_DIAGNOSTICS__

function showRuntimeError(title: string, detail: unknown) {
  const message = detail instanceof Error
    ? detail.stack || detail.message
    : String(detail ?? 'Unknown error')

  if (earlyDiagnostics) {
    earlyDiagnostics.mark('runtime-error')
    if (!earlyDiagnostics.errors.includes(message)) {
      earlyDiagnostics.errors.push(message.slice(0, 1200))
    }
  }

  // Render directly into the DOM so diagnostics still appear if Vue rendering fails.
  let panel = document.getElementById('enffas-runtime-error') as HTMLElement | null
  if (!panel) {
    panel = document.createElement('section')
    panel.id = 'enffas-runtime-error'
    panel.setAttribute('role', 'alert')
    panel.style.cssText = [
      'position:fixed', 'z-index:2147483647', 'inset:12px', 'overflow:auto',
      'padding:22px', 'background:#101522', 'color:#f5f7ff',
      'border:1px solid #ef6678', 'border-radius:12px',
      'font:14px/1.6 system-ui,sans-serif', 'box-shadow:0 12px 50px #000b',
      'white-space:pre-wrap', 'overflow-wrap:anywhere'
    ].join(';')
    document.body.appendChild(panel)
  }

  const heading = document.createElement('h2')
  heading.textContent = 'Enffas detected an application error'
  heading.style.margin = '0 0 8px'
  const summary = document.createElement('p')
  summary.textContent = title
  const stage = document.createElement('p')
  stage.textContent = 'Startup stage: ' + (earlyDiagnostics?.stage ?? 'unknown')
  const explanation = document.createElement('p')
  explanation.textContent = 'This diagnostic is generated by the app, similar to a React error overlay. Copy the error details below and send them to the developer.'
  const pre = document.createElement('pre')
  pre.style.cssText = 'white-space:pre-wrap;overflow-wrap:anywhere;background:#080c14;padding:14px;border-radius:8px'
  pre.textContent = message.slice(0, 12000)
  const reload = document.createElement('button')
  reload.type = 'button'
  reload.textContent = 'Reload page'
  reload.style.cssText = 'padding:9px 14px;border:1px solid #8290b3;border-radius:8px;background:#25314a;color:white;cursor:pointer'
  reload.addEventListener('click', () => window.location.reload())
  panel.replaceChildren(heading, summary, stage, explanation, pre, reload)
}

earlyDiagnostics?.mark('vue-module-entry')

try {
  const app = createApp(App)

  // Vue's equivalent of a global React-style runtime error reporter.
  app.config.errorHandler = (error, instance, info) => {
    const component = instance?.$options.name || instance?.$options.__name || 'unknown component'
    showRuntimeError('Vue error in ' + component + ' (' + info + ')', error)
  }

  app.config.warnHandler = (message, instance, trace) => {
    const warning = '[Vue warning] ' + message + (trace ? '\n' + trace : '')
    if (earlyDiagnostics && !earlyDiagnostics.errors.includes(warning)) {
      earlyDiagnostics.errors.push(warning.slice(0, 1200))
    }
  }

  earlyDiagnostics?.mark('vue-app-created')
  app.mount('#app')
  earlyDiagnostics?.mark('mount-complete')
} catch (error) {
  showRuntimeError('Vue failed while creating or mounting the application', error)
  throw error
}
